//  handover.h  ——  换引擎
//
//  ★为什么需要一个状态机, 而不是"点一下就切"★
//  两次实测崩溃(2026-09-04 23:56 / 2026-09-05 00:13, 都是燕云), 病因一模一样:
//  【交接的时候, 在位的那个从来没撒手, 后来的直接建了第二个 feature 18】。
//  NGX 一个进程只准活一个, 两个同时活 = DXGI_ERROR_DEVICE_REMOVED, 显卡当场掉线。
//
//  所以交接必须分帧走, 中间留出"谁都没拿着"的静置期:
//
//    033 → 主插件   我们真的放手 → 静置 90 帧 → 才把 RenoDX 叫醒
//                   ★这一条是稳的★ 两步都在我们自己手里, 不用赌别人。
//
//    主插件 → 033   先把 RenoDX 的开关关掉 → 给它 300 帧(约5秒)自己拆干净
//                   → 再静置 90 帧 → 我们才建
//                   ★这一条要赌 RenoDX 关掉开关之后真的会释放★
//                   赌的原因: 它的 feature 走的是运行库 nvngx_dlssnr.dll 那扇门,
//                   而那个运行库是社区签名版、自校验代码完整性, ★钩不得★
//                   (我们试过, 一钩就挂, 见 dlss5_033.cpp 里那段注释)。
//                   所以账本看不见它。看不见就只能给足时间 + 静置, 没有别的办法。
//                   上一次崩是因为只等了 1.5 秒还没静置 —— 现在是 6.5 秒。
//
//  账本(nrscale::other_owns)能看见的那部分, 变成一道硬闸: 只要账上还有别人的
//  feature 18, 我们一帧都不许建。它拦不住 RenoDX(看不见), 但拦得住游戏自己的、
//  以及任何走薄壳/核心那两扇门的家伙 —— 那正是我们能看见的全部。
// =====================================================================
#pragma once

namespace handover
{

// ═════════════════════════════════════════════════════════════════
//  ★结论: 有 RenoDX 在的进程里, 换引擎【做不到游戏内实时】★
//  2026-09-05 凌晨试了三轮, 一轮比一轮接近, 最后卡死在一堵物理墙上。
//
//  最后那次(00:50)的日志是决定性的 —— 交接流程本身完全正确:
//    00:50:15  [交接] 开始 → 我们把 NeuralUplift 置 0
//    00:50:19  [交接] 完成: 033 接手
//    00:50:24  RenoDX: first NGX evaluate intercepted   ← 游戏这才第一次调 DLSS
//    00:50:24  RenoDX: signed DLSSNR runtime initialized
//    00:50:25  RenoDX: feature 18 created               ← 照样抢走了
//    00:50:26  [hostnr] feature 18 被别人占着            ← 我们的闸拦对了
//
//  两条硬事实:
//   ① RenoDX 是【懒加载】的: 它在游戏第一次调 DLSS 的那一刻才初始化运行库、
//      建 feature 18。那个时刻由游戏决定(读条/菜单里根本不调), 跟我们的交接
//      没有先后关系 —— 我们等再久也没用, 它可能在我们等完之后才动手。
//   ② NeuralUplift 不是它的总开关, 只管后处理。真开关是 EnableHooks,
//      而钩子是它进程启动时装的, ★游戏里拆不掉★。
//
//  再加上 00:41 那次证明的另一面: 就算交接干净, 把活儿还给它也会死 ——
//  它接管时要把 DLSSNR 运行库重新 Init 一遍, 而这一局已经被我们驱动过,
//  对已有活会话双 Init = 显卡掉线(2026-09-03 就记过这条雷)。
//
//  所以两个方向都只剩一条路: ★写配置 + 重进游戏★
//  写的是 EnableHooks(真开关), 而且留到【进程退出时】才写 —— 在游戏里写
//  等于当场对它下命令。下次启动只有一个引擎有资格碰 NGX, 从根上没得抢。
// ═════════════════════════════════════════════════════════════════

static int  s_pending = -1;      // -1 没选过; 1 = 033; 0 = 主插件

static bool busy()   { return false; }        // 不再有分帧过程
static bool failed() { return false; }
static const char *note() { return ""; }
static int  target() { return s_pending; }
static float progress() { return 0.0f; }

static void start(bool own)
{
    s_pending = own ? 1 : 0;
    carrier::write_engine_choice(own);          // 我们这边的配置, 立刻落盘
    carrier::g_hooks_on_exit = own ? 0 : 2;     // RenoDX 的总开关, 退出时写
    Log("[换引擎] 已记下: %s (重进游戏生效; 本局不动手 —— 见 handover.h 顶上那段)",
        own ? "033 自研" : "主插件 RenoDX");
}

static void pump() { }                          // 没有分帧动作了, 留着接口

} // namespace handover
